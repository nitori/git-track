//! Runs scans off the UI thread.
//!
//! Every scan gets its own OS thread and streams results back through an
//! unbounded channel, which the UI drains in a foreground task:
//! * Windows: the core scanner runs in-process.
//! * WSL: `git-track-agent` is started via `wsl.exe` and its NDJSON output is
//!   forwarded line by line. Scanning natively inside WSL is far faster than
//!   accessing `\\wsl$` from Windows (or `/mnt/*` from WSL).
//!
//! Watchers (between full scans) work the same way, but keep running and
//! take [`WatchCommand`]s.

use std::io::{BufRead, BufReader, Read, Write};
use std::process::{Child, Command, Stdio};
use std::sync::{Mutex, mpsc};

use futures::channel::mpsc::{UnboundedReceiver, UnboundedSender, unbounded};
use git_track_core::{Event, ScanRequest, WatchCommand};
use serde::{Deserialize, Serialize};

use crate::config::{CARGO_AGENT, Config};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SourceKind {
    Windows,
    Wsl,
}

#[derive(Debug)]
pub enum Msg {
    Event(Event),
    /// The scan could not be run (or the agent died). Partial results may have been sent.
    Failed(String),
}

/// Which agent to run where.
struct Wsl {
    distro: Option<String>,
    custom_agent: Option<String>,
}

impl Wsl {
    fn new(config: &Config) -> Self {
        Self {
            distro: config.wsl.distro.clone().filter(|d| !d.is_empty()),
            custom_agent: config.wsl.custom_agent().map(String::from),
        }
    }

    /// The agent to run: the configured one, or the bundled one (installed
    /// first unless this run did that already).
    fn agent(&self) -> Result<String, String> {
        if let Some(agent) = &self.custom_agent {
            return Ok(agent.clone());
        }
        let Some((bytes, hash)) = bundled::AGENT else {
            return Ok(CARGO_AGENT.to_string());
        };
        let mut installed = INSTALLED.lock().unwrap_or_else(|e| e.into_inner());
        if !installed.contains(&self.distro) {
            install_agent(self.distro.as_deref(), bytes, hash)?;
            installed.push(self.distro.clone());
        }
        Ok(format!("~/{AGENT_DIR}/agent-{hash}"))
    }

    /// The agent could not be run: install it again next time.
    fn forget_agent(&self) {
        INSTALLED
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .retain(|d| *d != self.distro);
    }

    /// What to say when the agent did not work.
    fn agent_hint(&self, agent: &str) -> String {
        if self.custom_agent.is_some() || bundled::AGENT.is_none() {
            format!(
                "Is the agent installed? Expected at '{agent}' (inside WSL: cargo install --path crates/agent)"
            )
        } else {
            format!("The bundled agent was installed to '{agent}'.")
        }
    }
}

mod bundled {
    // Generated by build.rs: the agent binary and a hash of it.
    include!(concat!(env!("OUT_DIR"), "/agent.rs"));
}

/// Distributions the bundled agent was installed into during this run.
static INSTALLED: Mutex<Vec<Option<String>>> = Mutex::new(Vec::new());

/// Below the WSL home directory.
const AGENT_DIR: &str = ".local/share/git-track";

/// Installs the agent (from stdin) as `agent-<hash>` unless it is there.
/// Agents of other builds are removed once unused for a week (every run
/// touches its own).
const INSTALL_SCRIPT: &str = r#"[ "$(uname -m)" = x86_64 ] || exit 3
d="$HOME/.local/share/git-track"
f="$d/agent-$1"
if [ -x "$f" ]; then touch "$f"; exit 0; fi
mkdir -p "$d" || exit 1
find "$d" -maxdepth 1 -name 'agent-*' ! -name "agent-$1" -mtime +7 -delete 2>/dev/null
cat > "$f.tmp" && chmod 755 "$f.tmp" && mv -f "$f.tmp" "$f"
"#;

fn install_agent(distro: Option<&str>, bytes: &'static [u8], hash: &str) -> Result<(), String> {
    let mut cmd = Command::new("wsl.exe");
    if let Some(distro) = distro {
        cmd.args(["-d", distro]);
    }
    cmd.args(["-e", "sh", "-c", INSTALL_SCRIPT, "sh", hash])
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .stderr(Stdio::piped());
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        cmd.creation_flags(CREATE_NO_WINDOW);
    }
    let mut child = cmd
        .spawn()
        .map_err(|e| format!("cannot start wsl.exe: {e}"))?;
    let stdin = child.stdin.take();
    // Not read at all if the agent is installed already (broken pipe then).
    let writer = std::thread::spawn(move || {
        if let Some(mut stdin) = stdin {
            let _ = stdin.write_all(bytes);
        }
    });
    let out = child
        .wait_with_output()
        .map_err(|e| format!("installing the WSL agent: {e}"))?;
    let _ = writer.join();
    match out.status.code() {
        Some(0) => Ok(()),
        Some(3) => Err(format!(
            "The bundled WSL agent is built for x86_64 only. Build one inside WSL \
             (cargo install --path crates/agent) and set its path as [wsl] agent \
             in {}.",
            Config::path().display()
        )),
        _ => Err(format!(
            "Cannot install the WSL agent ({}): {}",
            out.status,
            decode_wsl_output(&out.stderr).trim()
        )),
    }
}

pub fn start(kind: SourceKind, request: ScanRequest, config: &Config) -> UnboundedReceiver<Msg> {
    let (tx, rx) = unbounded();
    let wsl = Wsl::new(config);
    let name = format!("git-track-{kind:?}").to_lowercase();
    let spawned = std::thread::Builder::new().name(name).spawn({
        let tx = tx.clone();
        move || match kind {
            SourceKind::Windows => run_local(&request, &tx),
            SourceKind::Wsl => run_wsl(&request, &wsl, &tx),
        }
    });
    if let Err(e) = spawned {
        let _ = tx.unbounded_send(Msg::Failed(format!("cannot start scan thread: {e}")));
    }
    rx
}

fn run_local(request: &ScanRequest, tx: &UnboundedSender<Msg>) {
    git_track_core::scan(request, &|event| {
        let _ = tx.unbounded_send(Msg::Event(event));
    });
}

/// Starts a watcher for the repositories of `kind` (see
/// `git_track_core::watch`). It runs until the returned sender is dropped;
/// for WSL that closes the agent's stdin, which ends it.
pub fn start_watch(
    kind: SourceKind,
    config: &Config,
) -> (mpsc::Sender<WatchCommand>, UnboundedReceiver<Msg>) {
    let (commands_tx, commands) = mpsc::channel();
    let (tx, rx) = unbounded();
    let wsl = Wsl::new(config);
    let name = format!("git-track-watch-{kind:?}").to_lowercase();
    let spawned = std::thread::Builder::new().name(name).spawn({
        let tx = tx.clone();
        move || match kind {
            SourceKind::Windows => git_track_core::watch::watch(commands, &|event| {
                let _ = tx.unbounded_send(Msg::Event(event));
            }),
            SourceKind::Wsl => run_wsl_watch(commands, &wsl, &tx),
        }
    });
    if let Err(e) = spawned {
        let _ = tx.unbounded_send(Msg::Failed(format!("cannot start watch thread: {e}")));
    }
    (commands_tx, rx)
}

/// `wsl.exe` running the agent with `args`, all pipes connected.
fn wsl_agent_command(distro: Option<&str>, agent: &str, args: &[&str]) -> Command {
    let mut cmd = Command::new("wsl.exe");
    if let Some(distro) = distro.filter(|d| !d.is_empty()) {
        cmd.args(["-d", distro]);
    }
    // `-e` runs the program without a shell (no quoting issues), so `~` is
    // not expanded; start in the home directory and use a relative path instead.
    if let Some(relative) = agent.strip_prefix("~/") {
        cmd.args(["--cd", "~", "-e", relative]);
    } else {
        cmd.args(["-e", agent]);
    }
    cmd.args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        cmd.creation_flags(CREATE_NO_WINDOW);
    }
    cmd
}

/// Drains stderr concurrently so a chatty agent cannot block on a full pipe.
fn read_stderr(child: &mut Child) -> impl FnOnce() -> String + use<> {
    let reader = child.stderr.take().map(|mut stderr| {
        std::thread::spawn(move || {
            let mut buf = Vec::new();
            let _ = stderr.read_to_end(&mut buf);
            buf
        })
    });
    move || {
        reader
            .and_then(|h| h.join().ok())
            .map(|b| decode_wsl_output(&b))
            .unwrap_or_default()
    }
}

struct Forwarded {
    /// `Done` or `Fatal` was received.
    done: bool,
    /// The first line that was no event.
    protocol_error: Option<String>,
}

/// Forwards the agent's NDJSON events until its stdout closes. `None`: the
/// UI is no longer interested (the agent was killed).
fn forward_events(child: &mut Child, tx: &UnboundedSender<Msg>) -> Option<Forwarded> {
    let mut forwarded = Forwarded {
        done: false,
        protocol_error: None,
    };
    let Some(stdout) = child.stdout.take() else {
        return Some(forwarded);
    };
    for line in BufReader::new(stdout).lines() {
        let Ok(line) = line else { break };
        if line.trim().is_empty() {
            continue;
        }
        match serde_json::from_str::<Event>(&line) {
            Ok(event) => {
                forwarded.done |= matches!(event, Event::Done { .. } | Event::Fatal { .. });
                if tx.unbounded_send(Msg::Event(event)).is_err() {
                    let _ = child.kill();
                    let _ = child.wait();
                    return None;
                }
            }
            Err(e) => {
                forwarded
                    .protocol_error
                    .get_or_insert_with(|| format!("unexpected agent output ({e}): {line}"));
            }
        }
    }
    Some(forwarded)
}

fn run_wsl_watch(commands: mpsc::Receiver<WatchCommand>, wsl: &Wsl, tx: &UnboundedSender<Msg>) {
    let fail = |msg: String| {
        let _ = tx.unbounded_send(Msg::Failed(msg));
    };
    let agent = match wsl.agent() {
        Ok(agent) => agent,
        Err(e) => return fail(e),
    };
    let mut child = match wsl_agent_command(wsl.distro.as_deref(), &agent, &["watch"]).spawn() {
        Ok(child) => child,
        Err(e) => return fail(format!("cannot start wsl.exe: {e}")),
    };
    if let Some(mut stdin) = child.stdin.take() {
        std::thread::spawn(move || {
            // Ends when the app drops the sender; closing stdin ends the agent.
            for command in commands {
                let Ok(line) = serde_json::to_string(&command) else {
                    continue;
                };
                if writeln!(stdin, "{line}").and_then(|_| stdin.flush()).is_err() {
                    break;
                }
            }
        });
    }
    let stderr = read_stderr(&mut child);
    let Some(forwarded) = forward_events(&mut child, tx) else {
        return;
    };
    let status = child.wait();
    let stderr = stderr();
    let stderr = stderr.trim();
    let failed = !status.as_ref().is_ok_and(|s| s.success());
    if failed || !stderr.is_empty() || forwarded.protocol_error.is_some() {
        if failed {
            wsl.forget_agent();
        }
        let mut msg = match status {
            Ok(s) => format!("WSL watcher exited ({s})"),
            Err(e) => format!("WSL watcher: {e}"),
        };
        for detail in [forwarded.protocol_error.as_deref(), Some(stderr)]
            .into_iter()
            .flatten()
            .filter(|d| !d.is_empty())
        {
            msg.push_str(&format!("\n{detail}"));
        }
        fail(msg);
    }
}

fn run_wsl(request: &ScanRequest, wsl: &Wsl, tx: &UnboundedSender<Msg>) {
    let fail = |msg: String| {
        let _ = tx.unbounded_send(Msg::Failed(msg));
    };
    let agent = match wsl.agent() {
        Ok(agent) => agent,
        Err(e) => return fail(e),
    };

    let mut child = match wsl_agent_command(wsl.distro.as_deref(), &agent, &["scan", "--stdin"])
        .spawn()
    {
        Ok(child) => child,
        Err(e) => return fail(format!("cannot start wsl.exe: {e}")),
    };

    let request_json = serde_json::to_string(request).unwrap_or_default();
    if let Some(mut stdin) = child.stdin.take() {
        // Dropping stdin closes it, which tells the agent the request is complete.
        let _ = stdin.write_all(request_json.as_bytes());
    }

    let stderr = read_stderr(&mut child);
    let Some(Forwarded {
        done,
        protocol_error,
    }) = forward_events(&mut child, tx)
    else {
        return;
    };

    let status = child.wait();
    let stderr = stderr();
    if !done {
        let mut msg = match status {
            Ok(s) => format!("WSL agent exited ({s}) without finishing"),
            Err(e) => format!("WSL agent: {e}"),
        };
        if let Some(p) = protocol_error {
            msg.push_str(&format!("\n{p}"));
        }
        let stderr = stderr.trim();
        if !stderr.is_empty() {
            msg.push_str(&format!("\n{stderr}"));
        }
        msg.push_str(&format!("\n{}", wsl.agent_hint(&agent)));
        wsl.forget_agent();
        fail(msg);
    }
}

/// `wsl.exe` prints its own messages as UTF-16LE, while the Linux side writes UTF-8.
fn decode_wsl_output(bytes: &[u8]) -> String {
    let odd_nuls = bytes.iter().skip(1).step_by(2).filter(|b| **b == 0).count();
    if bytes.len() >= 4 && odd_nuls * 2 >= bytes.len() / 2 {
        let units: Vec<u16> = bytes
            .as_chunks::<2>()
            .0
            .iter()
            .map(|c| u16::from_le_bytes(*c))
            .collect();
        String::from_utf16_lossy(&units)
    } else {
        String::from_utf8_lossy(bytes).into_owned()
    }
}

#[cfg(all(test, windows))]
mod tests {
    use super::*;

    #[test]
    #[ignore = "installs a dummy agent into the default WSL distribution"]
    fn installs_agent_through_wsl() {
        let script = b"#!/bin/sh\necho \"hi $1\"\n";
        install_agent(None, script, "test-only").unwrap();
        // Installed already: stdin is not read.
        install_agent(None, b"", "test-only").unwrap();
        let out = Command::new("wsl.exe")
            .args(["--cd", "~", "-e", ".local/share/git-track/agent-test-only", "there"])
            .output()
            .unwrap();
        let _ = Command::new("wsl.exe")
            .args(["--cd", "~", "-e", "rm", "-f", ".local/share/git-track/agent-test-only"])
            .output();
        assert_eq!(String::from_utf8_lossy(&out.stdout), "hi there\n");
    }
}
